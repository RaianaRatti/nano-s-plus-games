"""Builds the pet's physics facts: pet/facts/*.json -> pet/src/facts.c.

    python3 tools/make_facts.py

Each fact has a title (the concept, for the bar), the fact itself (what the pet says, in the box
over the room) and more (paragraphs that explain it, on the pages BOTH opens). The texts are
wrapped here, to the 20 characters a line holds on the screen. The facts are shuffled with a fixed
seed, so that one after the other they jump between topics; the pet tells them in that order.
"""

import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FACTS = ROOT / "pet" / "facts"
OUT = ROOT / "pet" / "src" / "facts.c"

LINE = 20       # characters per line
BOX_LINES = 5   # the fact, in the box over the room
PAGE_LINES = 6  # under the bar, on the pages (see pet/src/pet.c)
TITLE = 20      # the bar

# The letters the screen's font has beyond ASCII (see src/gfx.c).
GLYPHS = {"é": "\x06", "á": "\x07"}


def screen_text(text):
    out = "".join(GLYPHS.get(c, c) for c in text)
    bad = {c for c in out if not ("\x01" <= c <= "\x07" or " " <= c <= "_" or "a" <= c <= "z")}
    assert not bad, f"the font has no {bad} in {text!r}"
    return out


def wrap(text, width=LINE):
    lines, line = [], ""
    for word in screen_text(text).split():
        assert len(word) <= width, f"{word!r} is longer than a line"
        if line and len(line) + 1 + len(word) > width:
            lines.append(line)
            line = word
        else:
            line = f"{line} {word}" if line else word
    if line:
        lines.append(line)
    return lines


def pages_text(fact, more):
    """The fact, then the paragraphs, with an empty line between them (but none on top of a page)."""
    lines = list(fact)
    for paragraph in more:
        if len(lines) % PAGE_LINES:
            lines.append("")
        lines += wrap(paragraph)
    return lines


def c_string(s):
    out = ""
    for c in s:
        if c in '"\\':
            out += "\\" + c
        elif c == "\n":
            out += "\\n"
        elif ord(c) < 32:
            out += f"\\x{ord(c):02x}\"\""  # end the escape before the next character
        else:
            out += c
    return f'"{out}"'


def main():
    facts = []
    for path in sorted(FACTS.glob("*.json")):
        for fact in json.loads(path.read_text())["facts"]:
            facts.append((path.stem, fact))
    titles = [f["title"] for _, f in facts]
    assert len(set(titles)) == len(titles), "two facts have the same title"
    assert 0 < len(facts) <= 255, "the pet counts the facts in a byte"
    random.Random("mochi").shuffle(facts)

    text = ""
    table = []
    for topic, fact in facts:
        title = screen_text(fact["title"])
        assert len(title) <= TITLE, f"{title!r}: the title is too long for the bar"
        said = wrap(fact["fact"])
        assert len(said) <= BOX_LINES, f"{title!r}: the fact is {len(said)} lines, the box holds {BOX_LINES}"
        lines = pages_text(said, fact["more"])
        assert len(lines) <= 255
        title_at = len(text)
        text += title + "\0"
        text_at = len(text)
        text += "\n".join(lines) + "\0"
        table.append((title_at, text_at, len(said), len(lines)))
        print(f"{topic:11s} {title:20s} {len(lines):3d} lines ({-(-len(lines) // PAGE_LINES)} pages)")

    out = [
        "// Generated by tools/make_facts.py from pet/facts/*.json: do not edit.",
        "",
        '#include "facts.h"',
        "",
        f"const uint8_t NB_FACTS = {len(table)};",
        "",
        "const fact_t FACTS[] = {",
    ]
    for row in table:
        out.append("    {%d, %d, %d, %d}," % row)
    out += ["};", "", "const char FACT_TEXT[] ="]
    for chunk in text.split("\0")[:-1]:
        out.append(f"    {c_string(chunk + chr(0))}")
    out[-1] += ";"
    OUT.write_text("\n".join(out) + "\n")
    print(f"{len(table)} facts, {len(text)} bytes of text")


if __name__ == "__main__":
    main()
